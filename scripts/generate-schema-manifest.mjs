/**
 * Build the schema manifest the browser validator loads.
 *
 * Derived from the files actually present in static/schemas/, so the list of
 * validatable message types cannot drift from the list of schemas served. A
 * hardcoded map would eventually claim a schema that had been removed, or miss
 * one that had been added — the same class of drift this project keeps finding.
 *
 * Each schema is checked before it is listed: the target namespace must match
 * the filename, and the file must declare itself an XML Schema. A file that
 * fails either check fails the build rather than being silently skipped.
 */
import { readFileSync, writeFileSync, readdirSync } from "fs";
import { createHash } from "crypto";
import { join } from "path";

const schemaDir = join(process.cwd(), "static", "schemas");
const NS_PREFIX = "urn:iso:std:iso:20022:tech:xsd:";

const errors = [];
const entries = [];

for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".xsd")).sort()) {
  const contents = readFileSync(join(schemaDir, file), "utf8");
  const messageType = file.replace(/\.xsd$/, "");

  if (!/<xs:schema/.test(contents)) {
    errors.push(`${file}: does not declare an XML Schema`);
    continue;
  }

  const ns = contents.match(/targetNamespace="([^"]+)"/)?.[1];
  if (ns !== `${NS_PREFIX}${messageType}`) {
    errors.push(`${file}: targetNamespace is "${ns}", expected "${NS_PREFIX}${messageType}"`);
    continue;
  }

  if (/<xs:(import|include)\b/.test(contents)) {
    errors.push(`${file}: has imports or includes, so it is not self-contained`);
    continue;
  }

  entries.push({
    messageType,
    family: messageType.split(".").slice(0, 2).join("."),
    file,
    url: `/schemas/${file}`,
    namespace: ns,
    bytes: Buffer.byteLength(contents),
    sha256: `sha256:${createHash("sha256").update(contents).digest("hex")}`,
    // Newer schemas carry "ISO 20022 version : NNNN"; ones generated by the
    // older SWIFTStandards Workstation (2009-era) carry only a generator line.
    // Record whichever exists rather than inventing a version for the ones
    // that do not state one.
    isoVersion: contents.match(/ISO 20022 version\s*:\s*(\d+)/)?.[1] ?? null,
    provenance:
      contents.match(/<!--\s*(Generated by [^>]*?)\s*-->/)?.[1]?.trim() ?? null,
  });
}

if (errors.length > 0) {
  console.error("Schema manifest FAILED:");
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}

const manifest = {
  _comment:
    "Generated by scripts/generate-schema-manifest.mjs from static/schemas/. Do not edit by hand. Schemas are ISO 20022 Registration Authority material, served under the ISO 20022 Intellectual Property Right Policy — see /schemas/README.txt.",
  generated_from: "static/schemas/",
  count: entries.length,
  schemas: Object.fromEntries(entries.map((e) => [e.messageType, e])),
};

writeFileSync(
  join(schemaDir, "manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`
);

const families = [...new Set(entries.map((e) => e.family))].sort();
console.log(
  `Schema manifest: ${entries.length} schemas across ${families.length} families ` +
    `(${families.join(", ")}).`
);
